"""Build vector-mask metadata from approved sheets; never modify source RGB or PNG files.

Only pale paper connected to the sheet border is excluded. Enclosed white armor,
fabric and eye highlights remain intact. Runtime uses these runs as SVG clips.
Pillow is only an offline pixel reader, not a runtime/project dependency.
"""
from collections import deque
from pathlib import Path
import json
from PIL import Image

root = Path(__file__).resolve().parent.parent
names = ('asakura-yuu', 'tachibana-kairyu', 'minase-shiori')
result = {}
for name in names:
    im = Image.open(root / 'public/assets/characters/chapter-01-starter-v1' / (name + '.png')).convert('RGB')
    width, height = im.size
    rgb = list(im.get_flattened_data()) if hasattr(im, 'get_flattened_data') else list(im.getdata())
    paper = bytearray(min(p) >= 210 and max(p)-min(p) < 32 for p in rgb)
    outside = bytearray(width * height)
    queue = deque()
    def seed(index):
        if paper[index] and not outside[index]:
            outside[index] = 1
            queue.append(index)
    for x in range(width):
        seed(x)
        seed((height-1)*width+x)
    for y in range(height):
        seed(y*width)
        seed(y*width+width-1)
    while queue:
        i = queue.popleft()
        x, y = i % width, i // width
        if x: seed(i-1)
        if x < width-1: seed(i+1)
        if y: seed(i-width)
        if y < height-1: seed(i+width)
    rows = []
    for y in range(height):
        runs, x = [], 0
        while x < width:
            if outside[y*width+x]:
                x += 1
                continue
            start = x
            while x < width and not outside[y*width+x]: x += 1
            runs.extend((start, x))
        rows.append(runs)
    result[name] = rows
    print(name, 'background pixels:', sum(outside))
target = root / 'src/visual/starterMaskRuns.ts'
target.write_text('// Generated by scripts/build-starter-masks.py. Unchanged source pixels; SVG clip runs only.\nconst runs:Record<string,number[][]>=' + json.dumps(result, separators=(',', ':')) + ';\nexport default runs;\n', encoding='utf8')
print('Wrote vector mask runs:', target)
